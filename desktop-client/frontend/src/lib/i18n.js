export function normalizeLanguage(value) {
  return value === 'en' ? 'en' : 'pt-BR';
}

export function translate(locale, key, values = {}) {
  const template = messages[normalizeLanguage(locale)][key] ?? messages['pt-BR'][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
}

function loadLanguage() {
  try {
    return normalizeLanguage(localStorage.getItem(LANGUAGE_KEY));
  } catch {
    return 'pt-BR';
  }
}

export const language = writable(loadLanguage());
export const t = derived(language, (locale) => (key, values) => translate(locale, key, values));

export function setLanguage(value) {
  const locale = normalizeLanguage(value);
  language.set(locale);
  try {
    localStorage.setItem(LANGUAGE_KEY, locale);
  } catch {
    // The interface still changes for this session if storage is unavailable.
  }
}
